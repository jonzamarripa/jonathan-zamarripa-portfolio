// Precompiles the portfolio so visitors never download Babel or compile JSX in the browser.
// Usage: npm i -D @babel/core @babel/preset-react react@18.3.1 react-dom@18.3.1 && node build.cjs [path/to/_ds_bundle.js]
// Steps: compile → dist/site.js · prerender homepage HTML into index.html (#root) so crawlers, link previews and no-JS visitors get content.
const { readFileSync, writeFileSync, mkdirSync } = require('fs');
const { transformSync } = require('@babel/' + 'core');

const SITE_FILES = ['HomepageP1.jsx', 'Homepage.jsx', 'CaseStudyShell.jsx', 'CaseStudy-Legacy.jsx', 'CaseStudy-HotelKey.jsx', 'CaseStudy-GuestCRM.jsx', 'CaseStudy-Workday.jsx', 'CaseStudy-BehindTheBuild.jsx', 'App.jsx'];
const opts = { minified: true, comments: false, babelrc: false, configFile: false };
mkdirSync('dist', { recursive: true });

const src = SITE_FILES.map((f) => '\n/* ---- ' + f + ' ---- */\n' + readFileSync(f, 'utf8')).join('');
const code = transformSync(src, { ...opts, presets: ['@babel/preset-react'] }).code;
writeFileSync('dist/site.js', '/* Generated by build.cjs — edit the .jsx sources, then rebuild. */\n' + code);

const bundlePath = process.argv[2];
if (bundlePath) {
  const chunk = /\n\/\/ (\S+)\ntry \{ \(\(\) => \{\n[\s\S]*?\n\}\)\(\); \} catch \(e\) \{ __ds_ns\.__errors\.push\(\{ path: "([^"]+)"[^\n]*\n/g;
  const b = readFileSync(bundlePath, 'utf8').replace(chunk, (m, _p, p) => (/^(archive\/|behind-the-build-handoff|ui_kits\/|templates\/|scraps\/|uploads\/)/.test(p) ? '\n' : m));
  writeFileSync('dist/ds-core.js', '/* JIZ design-system components. Generated by build.cjs. */\n' + transformSync(b, opts).code);
}

// Prerender: minimal browser shims, then renderToString(Homepage). Effects don't run on the server.
try {
  const vm = require('vm');
  const React = require('react');
  const ReactDOMServer = require('react-dom/server');
  const noop = () => {};
  const el = () => ({ appendChild: noop, setAttribute: noop, style: {}, classList: { add: noop } });
  const win = {
    React, ReactDOMServer, location: { hash: '', pathname: '/', search: '' }, sessionStorage: { getItem: () => null, setItem: noop, removeItem: noop },
    matchMedia: () => ({ matches: false, addEventListener: noop, removeEventListener: noop }), addEventListener: noop, removeEventListener: noop,
    document: { getElementById: () => null, createElement: el, head: el(), documentElement: el(), querySelector: () => null }
  };
  win.window = win;
  const ctx = vm.createContext(win);
  vm.runInContext(readFileSync('dist/ds-core.js', 'utf8'), ctx);
  vm.runInContext(readFileSync('site-config.js', 'utf8'), ctx);
  vm.runInContext(readFileSync('content/journal.js', 'utf8'), ctx);
  vm.runInContext(code.replace(/ReactDOM\.createRoot\([^;]*\)\.render\([^;]*\);?\s*$/, ''), ctx);
  const html = ReactDOMServer.renderToString(React.createElement(win.HomepageExports.Homepage, { onOpenCaseStudy: noop })).replace(/<video\b[\s\S]*?<\/video>/g, '');
  const idx = readFileSync('index.html', 'utf8').replace(/<div id="root">[\s\S]*<\/div>\s*$/, '<div id="root"><div data-prerender="">' + html + '</div></div>\n');
  writeFileSync('index.html', idx);
  console.log('prerendered homepage into index.html');
} catch (e) { console.warn('prerender skipped:', e.message); }
console.log('built dist/site.js' + (bundlePath ? ' + dist/ds-core.js' : ''));
require('./build-journal.cjs');
